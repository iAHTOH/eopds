-- Миграция 1: базовая схема ядра (PostgreSQL).
-- Чистая установка. См. docs/db-schema.md.

-- Метаданные приложения/схемы (одна строка, id = 1).
CREATE TABLE app_meta (
    id            SMALLINT     PRIMARY KEY CHECK (id = 1),
    schema_version INTEGER     NOT NULL,
    app_version   TEXT         NOT NULL DEFAULT '',
    installed_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    last_scan_at  TIMESTAMPTZ
);

INSERT INTO app_meta (id, schema_version) VALUES (1, 1);

-- Применённые миграции.
CREATE TABLE schema_migrations (
    version     INTEGER      PRIMARY KEY,
    applied_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    description TEXT         NOT NULL DEFAULT ''
);

INSERT INTO schema_migrations (version, description) VALUES (1, 'baseline schema');

-- Кэш счётчиков (allbooks, allauthors, ...).
CREATE TABLE counters (
    name       TEXT        PRIMARY KEY,
    value      BIGINT      NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Журнал сканирований.
CREATE TABLE scan_runs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at   TIMESTAMPTZ,
    status        TEXT        NOT NULL DEFAULT 'running', -- running/ok/error
    books_added   BIGINT      NOT NULL DEFAULT 0,
    books_removed BIGINT      NOT NULL DEFAULT 0,
    books_skipped BIGINT      NOT NULL DEFAULT 0,
    error         TEXT
);

-- Дерево каталогов (папки, ZIP, INPX/INP).
CREATE TABLE catalogs (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id  BIGINT REFERENCES catalogs(id) ON DELETE CASCADE,
    name       TEXT        NOT NULL,
    path       TEXT        NOT NULL,
    kind       SMALLINT    NOT NULL DEFAULT 0, -- 0=dir,1=zip,2=inpx,3=inp
    size_bytes BIGINT      NOT NULL DEFAULT 0,
    mtime      TIMESTAMPTZ
);
CREATE INDEX catalogs_parent_name_idx ON catalogs (parent_id, name);
CREATE UNIQUE INDEX catalogs_path_uidx  ON catalogs (path);

-- Книги (1M+ строк).
CREATE TABLE books (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    catalog_id     BIGINT      NOT NULL REFERENCES catalogs(id) ON DELETE CASCADE,
    filename       TEXT        NOT NULL,
    path           TEXT        NOT NULL,
    format         TEXT        NOT NULL DEFAULT '',
    size_bytes     BIGINT      NOT NULL DEFAULT 0,
    title          TEXT        NOT NULL DEFAULT '',
    search_title   TEXT        NOT NULL DEFAULT '',
    original_title TEXT,
    annotation     TEXT        NOT NULL DEFAULT '',
    isbn           TEXT,
    publisher      TEXT,
    publish_year   INTEGER,
    docdate        TEXT        NOT NULL DEFAULT '',
    lang           TEXT        NOT NULL DEFAULT '',
    lang_code      SMALLINT    NOT NULL DEFAULT 9,
    kind           SMALLINT    NOT NULL DEFAULT 0,
    avail          SMALLINT    NOT NULL DEFAULT 2, -- 0=del,1=check,2=ok
    source         TEXT,
    external_id    TEXT,
    added_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX books_path_filename_uidx ON books (path, filename);
CREATE INDEX books_search_title_idx   ON books (search_title);
CREATE INDEX books_lang_title_idx     ON books (lang_code, search_title);
CREATE INDEX books_avail_idx          ON books (avail);
CREATE INDEX books_catalog_idx        ON books (catalog_id);

-- Авторы.
CREATE TABLE authors (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name        TEXT     NOT NULL,
    search_full_name TEXT     NOT NULL DEFAULT '',
    lang_code        SMALLINT NOT NULL DEFAULT 9
);
CREATE UNIQUE INDEX authors_full_name_uidx ON authors (full_name);
CREATE INDEX authors_search_name_idx ON authors (search_full_name);

-- Связь книга-автор.
CREATE TABLE book_authors (
    book_id   BIGINT NOT NULL REFERENCES books(id)   ON DELETE CASCADE,
    author_id BIGINT NOT NULL REFERENCES authors(id) ON DELETE CASCADE,
    PRIMARY KEY (book_id, author_id)
);
CREATE INDEX book_authors_author_idx ON book_authors (author_id, book_id);

-- Жанры.
CREATE TABLE genres (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       TEXT NOT NULL,
    section    TEXT NOT NULL DEFAULT '',
    subsection TEXT NOT NULL DEFAULT ''
);
CREATE UNIQUE INDEX genres_code_uidx ON genres (code);

-- Связь книга-жанр.
CREATE TABLE book_genres (
    book_id  BIGINT NOT NULL REFERENCES books(id)  ON DELETE CASCADE,
    genre_id BIGINT NOT NULL REFERENCES genres(id) ON DELETE CASCADE,
    PRIMARY KEY (book_id, genre_id)
);
CREATE INDEX book_genres_genre_idx ON book_genres (genre_id, book_id);

-- Серии.
CREATE TABLE series (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        TEXT     NOT NULL,
    search_title TEXT     NOT NULL DEFAULT '',
    lang_code    SMALLINT NOT NULL DEFAULT 9
);
CREATE UNIQUE INDEX series_title_uidx ON series (title);

-- Связь книга-серия.
CREATE TABLE book_series (
    book_id   BIGINT NOT NULL REFERENCES books(id)  ON DELETE CASCADE,
    series_id BIGINT NOT NULL REFERENCES series(id) ON DELETE CASCADE,
    seq_no    INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (book_id, series_id)
);
CREATE INDEX book_series_series_idx ON book_series (series_id, seq_no);

-- Пользователи. Роли: admin (root) / moderator / reader. Гость — аноним, не в БД.
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      TEXT        NOT NULL,
    email         TEXT,
    password_hash TEXT        NOT NULL DEFAULT '',
    role          TEXT        NOT NULL DEFAULT 'reader'
                  CHECK (role IN ('admin', 'moderator', 'reader')),
    is_root       BOOLEAN     NOT NULL DEFAULT FALSE,
    is_active     BOOLEAN     NOT NULL DEFAULT TRUE,
    notify_new_books    BOOLEAN NOT NULL DEFAULT FALSE,
    notify_new_versions BOOLEAN NOT NULL DEFAULT FALSE,
    messenger_kind TEXT,
    messenger_id   TEXT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_username_uidx ON users (username);
-- Ровно один root-админ.
CREATE UNIQUE INDEX users_root_uidx ON users (is_root) WHERE is_root;

-- Приглашения на email (Issues #3).
CREATE TABLE invites (
    id            TEXT        PRIMARY KEY,
    email         TEXT        NOT NULL,
    role          TEXT        NOT NULL DEFAULT 'reader'
                  CHECK (role IN ('admin', 'moderator', 'reader')),
    token         TEXT        NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at    TIMESTAMPTZ,
    accepted_at   TIMESTAMPTZ,
    created_by_id BIGINT      REFERENCES users(id) ON DELETE SET NULL
);
CREATE UNIQUE INDEX invites_token_uidx ON invites (token);

-- Заявки гостей на регистрацию.
CREATE TABLE registration_requests (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         TEXT        NOT NULL,
    message       TEXT,
    status        TEXT        NOT NULL DEFAULT 'new'
                  CHECK (status IN ('new', 'approved', 'rejected')),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    handled_at    TIMESTAMPTZ,
    handled_by_id BIGINT      REFERENCES users(id) ON DELETE SET NULL
);
CREATE INDEX registration_requests_status_idx ON registration_requests (status, created_at);

-- Аудит действий администрации.
CREATE TABLE audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id    BIGINT      REFERENCES users(id) ON DELETE SET NULL,
    actor_name  TEXT        NOT NULL DEFAULT '',
    action      TEXT        NOT NULL,
    target_type TEXT        NOT NULL,
    target_id   TEXT,
    details     TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX audit_log_created_idx ON audit_log (created_at);
CREATE INDEX audit_log_target_idx  ON audit_log (target_type, target_id);

-- Системные настройки (правит только админ): SMTP, боты, порог новинок и т.п.
CREATE TABLE settings (
    key           TEXT        PRIMARY KEY,
    value         TEXT        NOT NULL DEFAULT '',
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by_id BIGINT      REFERENCES users(id) ON DELETE SET NULL
);

-- Сессии.
CREATE TABLE sessions (
    id         TEXT        PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    data       TEXT        NOT NULL DEFAULT ''
);
CREATE INDEX sessions_user_idx ON sessions (user_id);

-- Полка и прогресс (Issues #2).
CREATE TABLE bookshelf (
    user_id      BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    book_id      BIGINT      NOT NULL REFERENCES books(id) ON DELETE CASCADE,
    added_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_read_at TIMESTAMPTZ,
    PRIMARY KEY (user_id, book_id)
);
CREATE INDEX bookshelf_user_read_idx ON bookshelf (user_id, last_read_at);

-- Закладки/позиция чтения (Issues #2).
CREATE TABLE bookmarks (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    book_id    BIGINT      NOT NULL REFERENCES books(id) ON DELETE CASCADE,
    position   TEXT        NOT NULL DEFAULT '',
    note       TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX bookmarks_user_book_idx ON bookmarks (user_id, book_id);

-- Внешние аннотации (Issues #1).
CREATE TABLE annotations_cache (
    book_id    BIGINT      PRIMARY KEY REFERENCES books(id) ON DELETE CASCADE,
    source     TEXT        NOT NULL DEFAULT '',
    text       TEXT        NOT NULL DEFAULT '',
    fetched_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Обложки: метаданные; изображения — файлами на диске.
CREATE TABLE book_covers (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id    BIGINT      NOT NULL REFERENCES books(id) ON DELETE CASCADE,
    kind       SMALLINT    NOT NULL DEFAULT 1, -- 1=thumb,2=full
    source     TEXT        NOT NULL DEFAULT 'extracted',
    format     TEXT        NOT NULL DEFAULT 'jpeg',
    width      INTEGER     NOT NULL DEFAULT 0,
    height     INTEGER     NOT NULL DEFAULT 0,
    size_bytes BIGINT      NOT NULL DEFAULT 0,
    file_path  TEXT        NOT NULL DEFAULT '',
    fetched_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX book_covers_book_kind_uidx ON book_covers (book_id, kind);

-- История скачиваний / «что читают» (дашборд).
CREATE TABLE downloads (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id       BIGINT      NOT NULL REFERENCES books(id) ON DELETE CASCADE,
    user_id       BIGINT      REFERENCES users(id) ON DELETE SET NULL,
    downloaded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    format        TEXT        NOT NULL DEFAULT ''
);
CREATE INDEX downloads_downloaded_at_idx ON downloads (downloaded_at);
CREATE INDEX downloads_book_idx          ON downloads (book_id);
