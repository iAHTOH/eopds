-- Миграция 6: оценки и отзывы пользователей к книгам.
--
-- Регистрация — только по приглашению, поэтому премодерации нет: отзыв
-- публикуется сразу. Пользователь может удалить свой отзыв; модератор/админ —
-- любой (права проверяются в коде).
--
-- book_ratings  — звёздный рейтинг. Шкала 0..10 (шаг 1) = 5 звёзд с
--                 половинками (0.5..5.0): score/2 даёт значение в звёздах.
--                 Одна оценка на пользователя на книгу (последняя перезаписывает).
-- book_comments — текстовые отзывы/впечатления.

CREATE TABLE book_ratings (
    book_id    BIGINT      NOT NULL REFERENCES books(id) ON DELETE CASCADE,
    user_id    BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    score      SMALLINT    NOT NULL CHECK (score >= 0 AND score <= 10),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (book_id, user_id)
);
CREATE INDEX book_ratings_user_idx ON book_ratings (user_id);

CREATE TABLE book_comments (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id    BIGINT      NOT NULL REFERENCES books(id)  ON DELETE CASCADE,
    user_id    BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    body       TEXT        NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX book_comments_book_idx ON book_comments (book_id, created_at DESC);
CREATE INDEX book_comments_user_idx ON book_comments (user_id);

UPDATE app_meta SET schema_version = 6 WHERE id = 1;
