-- Миграция 8: исходящая почта (SMTP), журнал отправок, токены подтверждения.
--
-- mail_smtp — единственная строка (id = 1) с настройками SMTP-сервера.
-- Пароль хранится в открытом виде осознанно: SMTP-AUTH требует исходный
-- секрет (хеш необратим), а конфигурация должна попадать в бэкап БД.
-- В интерфейс пароль никогда не отдаётся (поле маскируется).
--
-- mail_sent — журнал отправок (для раздела «Почта» и диагностики).
-- Время — unix ms (как system_events): одинаково для PG/SQLite.
--
-- email_tokens — одноразовые токены (сброс пароля, подтверждение адреса).
-- Хранится только SHA-256 от токена, сам токен уходит в письме.

CREATE TABLE mail_smtp (
    id             SMALLINT    PRIMARY KEY CHECK (id = 1),
    enabled        BOOLEAN     NOT NULL DEFAULT FALSE,
    host           TEXT        NOT NULL DEFAULT '',
    port           INTEGER     NOT NULL DEFAULT 587,
    security       TEXT        NOT NULL DEFAULT 'starttls'
                   CHECK (security IN ('smtps', 'starttls', 'none')),
    username       TEXT        NOT NULL DEFAULT '',
    password       TEXT        NOT NULL DEFAULT '',
    from_addr      TEXT        NOT NULL DEFAULT '',
    from_name      TEXT        NOT NULL DEFAULT '',
    reply_to       TEXT        NOT NULL DEFAULT '',
    -- Время последней успешной проверки/тестового письма (unix ms, 0 — никогда).
    verified_at    BIGINT      NOT NULL DEFAULT 0,
    verify_message TEXT        NOT NULL DEFAULT '',
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by_id  BIGINT      REFERENCES users(id) ON DELETE SET NULL
);

CREATE TABLE mail_sent (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts          BIGINT      NOT NULL,                     -- unix ms
    recipient   TEXT        NOT NULL,                     -- адрес получателя
    subject     TEXT        NOT NULL DEFAULT '',
    template    TEXT        NOT NULL DEFAULT '',          -- test|password_reset|verify_email
    status      TEXT        NOT NULL DEFAULT 'queued'     -- queued|sent|error
                CHECK (status IN ('queued', 'sent', 'error')),
    error       TEXT        NOT NULL DEFAULT '',
    message_id  TEXT        NOT NULL DEFAULT '',
    lang        TEXT        NOT NULL DEFAULT '',          -- язык письма
    user_id     BIGINT      REFERENCES users(id) ON DELETE SET NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX mail_sent_ts_idx        ON mail_sent (ts DESC);
CREATE INDEX mail_sent_recipient_idx ON mail_sent (recipient);

CREATE TABLE email_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    email      TEXT        NOT NULL,
    kind       TEXT        NOT NULL
               CHECK (kind IN ('reset_password', 'verify_email')),
    token_hash TEXT        NOT NULL,                      -- SHA-256 (hex)
    ts         BIGINT      NOT NULL,                      -- unix ms создания
    expires_at BIGINT      NOT NULL,                      -- unix ms истечения
    used_at    BIGINT      NOT NULL DEFAULT 0             -- unix ms использования
);
CREATE UNIQUE INDEX email_tokens_hash_uidx ON email_tokens (token_hash);
CREATE INDEX email_tokens_user_idx ON email_tokens (user_id, kind);

UPDATE app_meta SET schema_version = 8 WHERE id = 1;
